#!/usr/bin/env python3
"""Stage the complete Windows app payload for the separate Microsoft Store MSIX build."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import sys

from build_targets import mpdev_platform_name


ROOT = Path(__file__).resolve().parents[1]


def configure_store_msix_identity(
    package_config: dict,
    publisher: str,
    identity_name: str,
) -> bool:
    """Apply Partner Center identity only when both required values are present."""
    if bool(publisher) != bool(identity_name):
        raise ValueError(
            "Set both MSIX_PUBLISHER and MSIX_IDENTITY_NAME from Partner Center, "
            "or leave both unset for a development/test-signed package."
        )
    if not publisher:
        return False

    package_config["publisher"] = publisher
    package_config["packageName"] = identity_name
    package_config.setdefault("msix", {}).pop("digitalSignature", None)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--app-dir",
        type=Path,
        default=ROOT / "build" / "dist" / "windows-x64" / "app",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "build" / ".rcache" / "windows-store" / "source",
    )
    parser.add_argument("--platform", choices=("x64", "arm64", "x86"), default="x64")
    args = parser.parse_args()
    app_dir = args.app_dir.resolve()
    output = args.output.resolve()

    names = (
        "git-manager.exe",
        "gitm.exe",
        "gitmanager-setup.exe",
        "crash_helper.exe",
        "git-manager-service.exe",
        "GitManager-Setup.exe",
    )
    missing = [name for name in names if not (app_dir / name).is_file()]
    if missing:
        print("Windows app-only build is missing: " + ", ".join(missing), file=sys.stderr)
        return 1

    if output.exists():
        marker = output.parent / ".gitmanager-generated"
        if not marker.is_file():
            print(f"Refusing to replace unmarked staging directory: {output}", file=sys.stderr)
            return 1
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output.parent / ".gitmanager-generated").write_text(
        "Generated by tools/package_windows_store.py.\n", encoding="utf-8"
    )

    try:
        for name in names:
            source = app_dir / name
            destination = output / name
            shutil.copy2(source, destination)

        resources = output / "resources"
        resources.mkdir()
        for name in names[1:]:
            shutil.copy2(app_dir / name, resources / name)

        python_source = ROOT / "tools" / "runtime" / "python"
        python_required = ("python.exe", "python314.zip", "python314._pth")
        absent = [name for name in python_required if not (python_source / name).is_file()]
        if absent:
            raise FileNotFoundError("Private CPython runtime is incomplete: " + ", ".join(absent))
        shutil.copytree(python_source, resources / "python")

        cleaner = ROOT / "tools" / "gitmanager_cleaner.py"
        if not cleaner.is_file():
            raise FileNotFoundError(f"Cleaner source is missing: {cleaner}")
        tools_dir = resources / "tools"
        tools_dir.mkdir()
        shutil.copy2(cleaner, tools_dir / cleaner.name)

        required = (
            output / "git-manager.exe",
            resources / "gitm.exe",
            resources / "gitmanager-setup.exe",
            resources / "crash_helper.exe",
            resources / "git-manager-service.exe",
            resources / "python" / "python.exe",
            tools_dir / cleaner.name,
        )
        empty = [str(path.relative_to(output)) for path in required if not path.is_file() or path.stat().st_size == 0]
        if empty:
            raise FileNotFoundError("Staged MSIX payload is incomplete: " + ", ".join(empty))
    except OSError as error:
        print(f"Could not stage Microsoft Store payload: {error}", file=sys.stderr)
        return 1

    try:
        package_config = json.loads(
            (ROOT / "installer" / "store" / "msix" / "package.json").read_text(encoding="utf-8")
        )
        tauri_config = json.loads(
            (ROOT / "src-tauri" / "tauri.conf.json").read_text(encoding="utf-8")
        )
        version_parts = str(tauri_config.get("version", "")).split(".")
        if not version_parts or len(version_parts) > 4 or any(not part.isdigit() for part in version_parts):
            raise ValueError("Tauri version must contain one to four numeric components for MSIX.")
        version_parts.extend(["0"] * (4 - len(version_parts)))
        if any(int(part) > 65535 for part in version_parts):
            raise ValueError("MSIX version components cannot exceed 65535.")
        package_config["version"] = ".".join(version_parts)
        package_config["platform"] = mpdev_platform_name(args.platform)
        publisher = os.environ.get("MSIX_PUBLISHER", "").strip()
        identity_name = os.environ.get("MSIX_IDENTITY_NAME", "").strip()
        if configure_store_msix_identity(package_config, publisher, identity_name):
            # Store packages are signed by Microsoft after certification. Do not
            # ship MPDEV's development certificate in the Partner Center package.
            print("Partner Center identity configured; generating an unsigned Store-upload MSIX.")
        else:
            print(
                "Warning: configure both MSIX_PUBLISHER and MSIX_IDENTITY_NAME from Partner Center. "
                "This build will retain the development test certificate."
            )
        generated_manifest = output.parent / "package.json"
        generated_manifest.write_text(
            json.dumps(package_config, indent=2) + "\n",
            encoding="utf-8",
        )
    except (OSError, json.JSONDecodeError, ValueError) as error:
        print(f"Could not prepare the MSIX package definition: {error}", file=sys.stderr)
        return 1

    print(f"Staged complete MSIX payload: {output}")
    print(f"Generated MPDEV package definition: {generated_manifest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

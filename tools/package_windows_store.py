#!/usr/bin/env python3
"""Stage the complete Windows app payload for the separate Microsoft Store MSIX build."""

from __future__ import annotations

import argparse
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--app-dir",
        type=Path,
        default=ROOT / "build" / "dist" / "windows-x64" / "app",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "build" / ".rcache" / "windows-store" / "source",
    )
    args = parser.parse_args()
    app_dir = args.app_dir.resolve()
    output = args.output.resolve()

    names = (
        "git-manager.exe",
        "gitm.exe",
        "gitmanager-setup.exe",
        "crash_helper.exe",
        "git-manager-service.exe",
        "GitManager-Setup.exe",
    )
    missing = [name for name in names if not (app_dir / name).is_file()]
    if missing:
        print("Windows app-only build is missing: " + ", ".join(missing), file=sys.stderr)
        return 1

    if output.exists():
        marker = output.parent / ".gitmanager-generated"
        if not marker.is_file():
            print(f"Refusing to replace unmarked staging directory: {output}", file=sys.stderr)
            return 1
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output.parent / ".gitmanager-generated").write_text(
        "Generated by tools/package_windows_store.py.\n", encoding="utf-8"
    )

    try:
        for name in names:
            source = app_dir / name
            destination = output / name
            shutil.copy2(source, destination)

        resources = output / "resources"
        resources.mkdir()
        for name in names[1:]:
            shutil.copy2(app_dir / name, resources / name)

        python_source = ROOT / "tools" / "runtime" / "python"
        python_required = ("python.exe", "python314.zip", "python314._pth")
        absent = [name for name in python_required if not (python_source / name).is_file()]
        if absent:
            raise FileNotFoundError("Private CPython runtime is incomplete: " + ", ".join(absent))
        shutil.copytree(python_source, resources / "python")

        cleaner = ROOT / "tools" / "gitmanager_cleaner.py"
        if not cleaner.is_file():
            raise FileNotFoundError(f"Cleaner source is missing: {cleaner}")
        tools_dir = resources / "tools"
        tools_dir.mkdir()
        shutil.copy2(cleaner, tools_dir / cleaner.name)

        required = (
            output / "git-manager.exe",
            resources / "gitm.exe",
            resources / "gitmanager-setup.exe",
            resources / "crash_helper.exe",
            resources / "git-manager-service.exe",
            resources / "python" / "python.exe",
            tools_dir / cleaner.name,
        )
        empty = [str(path.relative_to(output)) for path in required if not path.is_file() or path.stat().st_size == 0]
        if empty:
            raise FileNotFoundError("Staged MSIX payload is incomplete: " + ", ".join(empty))
    except OSError as error:
        print(f"Could not stage Microsoft Store payload: {error}", file=sys.stderr)
        return 1

    print(f"Staged complete MSIX payload: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
